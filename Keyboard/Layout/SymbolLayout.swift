import Foundation

/// 符号/数字页键位模型（仅数据，渲染在键盘 UI 层）。
///
/// 与字母页的区别：本页按键**不透传引擎**——点击时由 UI 层先提交当前组合串
/// （若有），再把字面量直接插入文档。原因：中文全角标点在 X11 keysym 里
/// 没有对应码位，无法用 RimeKey 表达；而英文标点若透传引擎，其全角转换
/// 取决于 schema 的 ascii_punct 状态，不如字面量直插可预期。
/// 数字同理处理（有组合时先上屏首选再插数字，避免数字被引擎当作选词键）。
public enum SymbolLayout {
/// 第一行：数字。
public static let digitRow: [String] = ["1", "2", "3", "4", "5", "6", "7", "8", "9", "0"]

/// 第二、三行：常用中文标点（与任务定版清单一致）。
public static let punctRows: [[String]] = [
["。", "，", "？", "！", "：", "；", "、", "·", "…", "—"],
["（", "）", "", "“", "”", "‘", "’", "《", "》"],
]

/// 第四行补充：货币、百分、分隔符与分词符（' 在全拼里是分词键，
/// 但在符号页按字面量插入已上屏文本，与引擎内分词是两回事）。
public static let extraRow: [String] = ["￥", "%", "@", "#", "/", "_", "-", "+", "=", "'"]

/// 表情页签（实现轮 4）：36 个常用 emoji，视图层按 9 列 × 4 行网格排布，
/// 点按与符号同路径直插（先提交组合串再直插）。
public static let emojiGrid: [String] = [
    "😀", "😁", "😂", "🤣", "😊", "😍", "😘", "😎", "🤔",
    "😅", "😴", "😭", "😱", "🤝", "👍", "👏", "🙏", "💪",
    "👀", "🎉", "❤️", "🔥", "💯", "🌹", "🍺", "☕", "🚗",
    "✈️", "🏠", "💰", "📱", "🎂", "🐶", "🐱", "🌙", "⭐",
]
}
